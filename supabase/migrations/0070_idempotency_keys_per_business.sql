  where membership_id = v_membership and check_out is null
  order by check_in desc limit 1;

  if found then
    update attendance_record set check_out = now() where id = v_open.id;
    return jsonb_build_object('record_id', v_open.id, 'action', 'checked_out');
  end if;

  insert into attendance_record (
    client_ref, business_id, location_id, membership_id, check_in, source
  ) values (
    p->>'client_ref',
    (p->>'business_id')::uuid,
    nullif(p->>'location_id', '')::uuid,
    v_membership,
    now(),
    coalesce(p->>'source', 'mobile')
  )
  on conflict (business_id, client_ref) do nothing
  returning id into v_open.id;

  return jsonb_build_object('record_id', v_open.id, 'action', 'checked_in');
end;
$$;

-- complete_refund (latest definition was 0029_refunds_settlement.sql)
create or replace function complete_refund(p jsonb)
returns jsonb
language plpgsql security definer
as $$
declare
  v_request refund_request%rowtype;
  v_original payment%rowtype;
  v_refund_payment uuid;
  v_paid numeric(14,2);
  v_doc document%rowtype;
begin
  select * into v_request from refund_request
  where provider_reference = p->>'provider_reference'
     or id = nullif(p->>'refund_id', '')::uuid
  for update;

  if not found then
    raise exception 'refund_not_found';
  end if;
  if v_request.status = 'completed' then
    return jsonb_build_object('refund_id', v_request.id, 'duplicate', true);
  end if;

  select * into v_original from payment where id = v_request.payment_id;

  insert into payment (
    client_ref, business_id, customer_id, method, status, verification,
    amount, currency_code, provider, provider_reference,
    source_entity_type, source_entity_id, reversal_of, occurred_at
  ) values (
    'refund:' || v_request.id::text,
    v_request.business_id, v_original.customer_id, v_original.method,
    'refunded', 'provider_confirmed',
    v_request.amount, v_request.currency_code, v_original.provider,
    p->>'provider_reference',
    v_original.source_entity_type, v_original.source_entity_id,
    v_original.id,
    now()
  )
  on conflict (business_id, client_ref) do nothing
  returning id into v_refund_payment;

  if v_refund_payment is null then
    select id into v_refund_payment from payment
    where client_ref = 'refund:' || v_request.id::text
      and business_id = v_request.business_id;
  end if;

  update refund_request
  set status = 'completed',
      provider_reference = coalesce(p->>'provider_reference', provider_reference),
      refund_payment_id = v_refund_payment,
      completed_at = now()
  where id = v_request.id;

  -- Money leaving is a refund, not negative revenue.
  insert into ledger_entry (
    business_id, kind, amount, currency_code,
    source_entity_type, source_entity_id, business_date
  ) values (
    v_request.business_id, 'refund', -1 * v_request.amount, v_request.currency_code,
    'payment', v_refund_payment, current_date
  );

  -- Unwind whatever the original payment settled.
  if v_original.source_entity_type = 'document' then
    update receivable
    set amount_paid = greatest(amount_paid - v_request.amount, 0),
        settled_at = null
    where source_entity_type = 'document'
      and source_entity_id = v_original.source_entity_id;

    select * into v_doc from document where id = v_original.source_entity_id;
    select coalesce(sum(amount), 0) into v_paid
    from payment
    where source_entity_type = 'document'
      and source_entity_id = v_original.source_entity_id
      and status = 'confirmed';

    update document
    set status = case
          when v_paid <= 0 then 'issued'::document_status
          when v_paid >= coalesce(v_doc.total, 0) then 'paid'::document_status
          else 'partially_paid'::document_status end,
        updated_at = now()
    where id = v_original.source_entity_id;

  elsif v_original.source_entity_type = 'service_booking' then
    update service_booking
    set deposit_paid = greatest(deposit_paid - v_request.amount, 0),
        updated_at = now()
    where id = v_original.source_entity_id;
  end if;

  insert into event_outbox (
    event_type, business_id, channel, product_set,
    entity_type, entity_id, amount, currency_code, verification,
    correction_of, payload, business_date
  ) values (
    'finance.payment.refunded', v_request.business_id, 'system',
    case v_original.source_entity_type
      when 'document' then 'documents'
      when 'shop_order' then 'shop'
      when 'service_booking' then 'services'
      else 'readiness' end,
    'payment', v_refund_payment, v_request.amount, v_request.currency_code,
    'provider_confirmed',
    null,
    jsonb_build_object('refund_of', v_original.id, 'reason', v_request.reason),
    current_date
  );

  return jsonb_build_object(
    'refund_id', v_request.id,
    'refund_payment_id', v_refund_payment,
    'duplicate', false
  );
end;
$$;

-- execute_sale_reversal (latest definition was 0031_pos_refunds_discounts.sql)
create or replace function execute_sale_reversal(p jsonb)
returns jsonb
language plpgsql security definer
as $$
declare
  v_sale sale%rowtype;
  v_reversal uuid;
  v_line record;
  v_actor uuid := nullif(p->>'actor_membership_id', '')::uuid;
begin
  select * into v_sale from sale where id = (p->>'sale_id')::uuid for update;
  if not found then
    raise exception 'sale_not_found';
  end if;
  if v_sale.status = 'reversed' then
    return jsonb_build_object('sale_id', v_sale.id, 'duplicate', true);
  end if;

  insert into sale (
    client_ref, business_id, location_id, device_id, shift_id,
    cashier_membership_id, customer_id, status,
    subtotal, discount_total, tax_total, total, currency_code,
    note, receipt_number, reversal_of, occurred_at, business_date
  ) values (
    'reversal:' || v_sale.id::text,
    v_sale.business_id, v_sale.location_id, v_sale.device_id, v_sale.shift_id,
    v_actor, v_sale.customer_id, 'completed',
    -1 * v_sale.subtotal, -1 * v_sale.discount_total, -1 * v_sale.tax_total,
    -1 * v_sale.total, v_sale.currency_code,
    'Reversal of ' || v_sale.receipt_number,
    v_sale.receipt_number || '-R',
    v_sale.id,
    now(), current_date
  )
  on conflict (business_id, client_ref) do nothing
  returning id into v_reversal;

  if v_reversal is null then
    select id into v_reversal from sale where client_ref = 'reversal:' || v_sale.id::text and business_id = v_sale.business_id;
    return jsonb_build_object('sale_id', v_sale.id, 'reversal_id', v_reversal, 'duplicate', true);
  end if;

  -- The original is marked reversed but its content is untouched.
  update sale set status = 'reversed' where id = v_sale.id;

  -- Goods come back to the shelf.
  for v_line in
    select l.item_id, l.variant_id, l.quantity, l.description, ci.track_stock
    from sale_line l
    join catalogue_item ci on ci.id = l.item_id
    where l.sale_id = v_sale.id
  loop
    if v_line.track_stock then
      insert into stock_movement (
        client_ref, business_id, location_id, item_id, variant_id,
        kind, quantity, reason, source_entity_type, source_entity_id,
        actor_membership_id, occurred_at
      ) values (
        'reversal:' || v_sale.id::text || ':' || v_line.item_id,
        v_sale.business_id, v_sale.location_id, v_line.item_id, v_line.variant_id,
        'customer_return', v_line.quantity,
        'sale reversed', 'sale', v_reversal, v_actor, now()
      ) on conflict (business_id, client_ref) do nothing;
    end if;
  end loop;

  insert into ledger_entry (
    business_id, location_id, kind, amount, currency_code,
    source_entity_type, source_entity_id, business_date
  ) values (
    v_sale.business_id, v_sale.location_id, 'refund',
    -1 * v_sale.total, v_sale.currency_code, 'sale', v_reversal, current_date
  );

  insert into event_outbox (
    event_type, business_id, location_id, actor_membership_id,
    channel, product_set, entity_type, entity_id,
    amount, currency_code, verification, correction_of, payload, business_date
  ) values (
    'pos.sale.reversed', v_sale.business_id, v_sale.location_id, v_actor,
    'business_mobile', 'pos', 'sale', v_reversal,
    v_sale.total, v_sale.currency_code, 'merchant_declared', null,
    jsonb_build_object('reversal_of', v_sale.receipt_number),
    current_date
  );

  return jsonb_build_object('sale_id', v_sale.id, 'reversal_id', v_reversal, 'duplicate', false);
end;
$$;

-- record_stock_movement (latest definition was 0035_stock_entry.sql)
create or replace function record_stock_movement(p jsonb)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_kind movement_kind := (p->>'kind')::movement_kind;
  v_item catalogue_item%rowtype;
  v_business uuid := (p->>'business_id')::uuid;
  v_location uuid := (p->>'location_id')::uuid;
  v_reason text := nullif(trim(coalesce(p->>'reason', '')), '');
  v_counted numeric(14,3);
  v_current numeric(14,3);
  v_quantity numeric(14,3);
  v_client_ref text := nullif(p->>'client_ref', '');
  v_id uuid;
begin
  select * into v_item from catalogue_item where id = (p->>'item_id')::uuid;
  if not found or v_item.business_id <> v_business then
    raise exception 'item_not_found';
  end if;

  -- Only these arrive through this door. Sales, returns and transfers are
  -- written by the flows that own them.
  if v_kind not in ('opening_balance', 'restock', 'damage_loss', 'count_correction') then
    raise exception 'unsupported_movement_kind';
  end if;

  -- Writing stock off, or overriding a count, needs a stated reason: these
  -- are the two movements that hide theft if left unexplained (POS-INV-005).
  if v_kind in ('damage_loss', 'count_correction') and v_reason is null then
    raise exception 'reason_required';
  end if;

  if v_kind = 'count_correction' then
    -- The caller sends what they counted, not a delta. The difference is
    -- computed here so the balance lands exactly on the counted figure
    -- without the record ever being overwritten.
    v_counted := (p->>'counted_quantity')::numeric;
    if v_counted is null or v_counted < 0 then
      raise exception 'counted_quantity_required';
    end if;
    select coalesce(sum(quantity), 0) into v_current
    from stock_movement
    where business_id = v_business and location_id = v_location
      and item_id = v_item.id
      and kind not in ('reservation', 'reservation_release');
    v_quantity := v_counted - v_current;

    -- A count that agrees with the record is worth nothing to store.
    if v_quantity = 0 then
      return jsonb_build_object('movement_id', null, 'quantity', 0, 'no_change', true);
    end if;
  else
    v_quantity := (p->>'quantity')::numeric;
    if v_quantity is null or v_quantity = 0 then
      raise exception 'quantity_required';
    end if;
    -- Loss is always a reduction, however the caller phrased it.
    if v_kind = 'damage_loss' then
      v_quantity := -abs(v_quantity);
    else
      v_quantity := abs(v_quantity);
    end if;
  end if;

  insert into stock_movement (
    client_ref, business_id, location_id, item_id,
    kind, quantity, unit_cost, reason,
    actor_membership_id, occurred_at
  ) values (
    v_client_ref, v_business, v_location, v_item.id,
    v_kind, v_quantity, nullif(p->>'unit_cost', '')::numeric, v_reason,
    nullif(p->>'actor_membership_id', '')::uuid, now()
  )
  on conflict (business_id, client_ref) do nothing
  returning id into v_id;

  if v_id is null then
    select id into v_id from stock_movement where client_ref = v_client_ref and business_id = v_business;
    return jsonb_build_object('movement_id', v_id, 'duplicate', true);
  end if;

  -- Receiving stock is the moment an item becomes worth tracking. A
  -- merchant who counts their goods in should not also have to find a
  -- switch before the till shows the number.
  if v_kind in ('opening_balance', 'restock') and not v_item.track_stock then
    update catalogue_item set track_stock = true, updated_at = now()
    where id = v_item.id;
  end if;

  insert into event_outbox (
    event_type, business_id, location_id, actor_membership_id,
    channel, product_set, entity_type, entity_id,
    verification, payload, business_date
  ) values (
    'inventory.movement.recorded', v_business, v_location,
    nullif(p->>'actor_membership_id', '')::uuid,
    'business_mobile', 'pos', 'stock_movement', v_id,
    'merchant_declared',
    jsonb_build_object('kind', v_kind, 'quantity', v_quantity, 'item', v_item.name),
    current_date
  );

  return jsonb_build_object('movement_id', v_id, 'quantity', v_quantity, 'duplicate', false);
end;
$$;

