as $$
declare
  v_existing sale%rowtype;
  v_sale_id uuid;
  v_line jsonb;
  v_pay jsonb;
  v_business uuid := (p->>'business_id')::uuid;
  v_location uuid := (p->>'location_id')::uuid;
