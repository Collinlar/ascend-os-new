      'expected_cash', v_expected,
      'declared_cash', v_declared,
      'difference', v_difference,
      'cash_sales', v_cash_sales,
      'till_expenses', v_expenses
    ),
    current_date,
    coalesce((p->>'closed_at')::timestamptz, now())
  );

  return jsonb_build_object(
    'shift_id', v_shift.id,
    'expected_cash', v_expected,
    'declared_cash', v_declared,
    'difference', v_difference,
    'duplicate', false
  );
end;
