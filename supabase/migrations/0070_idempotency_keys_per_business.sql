    coalesce(p->>'currency_code', 'GHS'),
    p->>'note',
    p->>'receipt_number',
    (p->>'occurred_at')::timestamptz,
    coalesce((p->>'business_date')::date, ((p->>'occurred_at')::timestamptz)::date)
  )
  returning id into v_sale_id;

  for v_line in select * from jsonb_array_elements(p->'lines')
  loop
    insert into sale_line (
      sale_id, item_id, variant_id, description,
      quantity, unit_price, discount, tax, line_total
    ) values (
      v_sale_id,
      (v_line->>'item_id')::uuid,
      nullif(v_line->>'variant_id', '')::uuid,
      v_line->>'description',
      (v_line->>'quantity')::numeric,
      (v_line->>'unit_price')::numeric,
      coalesce((v_line->>'discount')::numeric, 0),
      coalesce((v_line->>'tax')::numeric, 0),
      (v_line->>'line_total')::numeric
    );

    if coalesce((v_line->>'track_stock')::boolean, false) then
      insert into stock_movement (
        client_ref, business_id, location_id, item_id, variant_id,
        kind, quantity, source_entity_type, source_entity_id,
        actor_membership_id, device_id, occurred_at
      ) values (
        v_client_ref || ':mv:' || (v_line->>'item_id'),
        v_business, v_location,
        (v_line->>'item_id')::uuid,
        nullif(v_line->>'variant_id', '')::uuid,
        'sale',
        -1 * (v_line->>'quantity')::numeric,
        'sale', v_sale_id,
        nullif(p->>'cashier_membership_id', '')::uuid,
        nullif(p->>'device_id', '')::uuid,
        (p->>'occurred_at')::timestamptz
      ) on conflict (business_id, client_ref) do nothing;
    end if;
  end loop;

  for v_pay in select * from jsonb_array_elements(p->'payments')
  loop
    insert into payment (
      client_ref, business_id, location_id, customer_id,
      method, status, verification, amount, currency_code, tendered,
      provider, provider_reference,
      source_entity_type, source_entity_id,
      actor_membership_id, device_id, occurred_at
    ) values (
      v_client_ref || ':pay:' || coalesce(v_pay->>'seq', '0'),
      v_business, v_location,
      nullif(p->>'customer_id', '')::uuid,
      (v_pay->>'method')::payment_method,
      coalesce((v_pay->>'status')::payment_status, 'confirmed'),
      'merchant_declared',
      (v_pay->>'amount')::numeric,
      coalesce(p->>'currency_code', 'GHS'),
      nullif(v_pay->>'tendered', '')::numeric,
      v_pay->>'provider',
      v_pay->>'provider_reference',
      'sale', v_sale_id,
      nullif(p->>'cashier_membership_id', '')::uuid,
      nullif(p->>'device_id', '')::uuid,
      (p->>'occurred_at')::timestamptz
    ) on conflict (business_id, client_ref) do nothing;
  end loop;

  insert into ledger_entry (
    business_id, location_id, kind, amount, currency_code,
    source_entity_type, source_entity_id, business_date
  ) values (
    v_business, v_location, 'sale_revenue',
    (p->>'total')::numeric,
    coalesce(p->>'currency_code', 'GHS'),
    'sale', v_sale_id,
    coalesce((p->>'business_date')::date, ((p->>'occurred_at')::timestamptz)::date)
  );

  insert into event_outbox (
    event_type, business_id, location_id, actor_membership_id,
    channel, product_set, entity_type, entity_id,
    amount, currency_code, verification, payload, business_date, occurred_at
  ) values (
    'pos.sale.completed', v_business, v_location,
    nullif(p->>'cashier_membership_id', '')::uuid,
    'pos_terminal', 'pos', 'sale', v_sale_id,
    (p->>'total')::numeric,
    coalesce(p->>'currency_code', 'GHS'),
    'merchant_declared',
    jsonb_build_object('client_ref', v_client_ref, 'line_count', jsonb_array_length(p->'lines')),
    coalesce((p->>'business_date')::date, ((p->>'occurred_at')::timestamptz)::date),
    (p->>'occurred_at')::timestamptz
  );

  return jsonb_build_object(
    'sale_id', v_sale_id,
    'receipt_number', p->>'receipt_number',
    'duplicate', false
  );
end;
$$;

-- complete_pos_sale_safe (latest definition was 0041_receipt_collision_recovery.sql)
create or replace function complete_pos_sale_safe(p jsonb)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_business uuid := (p->>'business_id')::uuid;
  v_device uuid := nullif(p->>'device_id', '')::uuid;
  v_wanted text := p->>'receipt_number';
  v_taken boolean;
  v_next int;
  v_prefix text;
  v_new text;
  v_result jsonb;
begin
  -- Already landed under its own client_ref: nothing to do, and certainly
  -- nothing to renumber.
  if exists (select 1 from sale where client_ref = p->>'client_ref' and business_id = v_business) then
    return complete_pos_sale(p);
  end if;

  select true into v_taken from sale
  where business_id = v_business and receipt_number = v_wanted
  limit 1;

  if v_taken is not true then
    return complete_pos_sale(p);
  end if;

  -- Keep the till's own prefix, take the next free number after everything
  -- it has already issued.
  v_prefix := regexp_replace(v_wanted, '-([0-9]+)$', '');
  v_next := greatest(device_receipt_high(v_device), 0) + 1;

  loop
    v_new := v_prefix || '-' || lpad(v_next::text, 4, '0');
    exit when not exists (
      select 1 from sale where business_id = v_business and receipt_number = v_new
    );
    v_next := v_next + 1;
  end loop;

  v_result := complete_pos_sale(
    p
    || jsonb_build_object('receipt_number', v_new)
    || jsonb_build_object(
         'note',
         trim(both ' ' from coalesce(p->>'note', '') || ' Reissued from ' || v_wanted)
       )
  );

  insert into audit_log (
    business_id, actor_membership_id, action, entity_type, entity_id, detail
  ) values (
    v_business, nullif(p->>'cashier_membership_id', '')::uuid,
    'pos.receipt.reissued', 'sale', (v_result->>'sale_id')::uuid,
    jsonb_build_object('was', v_wanted, 'now', v_new)
  );

  return v_result || jsonb_build_object('reissued_from', v_wanted, 'receipt_number', v_new);
end;
$$;

-- place_shop_order (latest definition was 0064_one_customer_record.sql)
create or replace function place_shop_order(p jsonb)
returns jsonb
language plpgsql security definer
as $$
declare
  v_business uuid := (p->>'business_id')::uuid;
  v_client_ref text := p->>'client_ref';
  v_existing shop_order%rowtype;
  v_customer uuid;
  v_location uuid;
  v_order uuid;
  v_line jsonb;
  v_item record;
  v_unit numeric(14,2);
  v_qty numeric(14,3);
  v_subtotal numeric(14,2) := 0;
  v_line_count int := 0;
begin
  if v_client_ref is null then
    raise exception 'client_ref is required';
  end if;

  select * into v_existing from shop_order where client_ref = v_client_ref and business_id = v_business;
  if found then
    return jsonb_build_object('order_id', v_existing.id, 'duplicate', true);
  end if;

  -- One shared customer record per business, matched on the normalised
  -- number rather than the raw one (CAP-003, 0064). The lookup used to live
  -- here and compared strings, which is how one person became two records.
  v_customer := nullif(find_or_create_customer(jsonb_build_object(
    'business_id', v_business,
    'name', p->>'customer_name',
    'phone', p->>'customer_phone',
    'email', p->>'customer_email',
    'created_via', 'shop'
  ))->>'customer_id', '')::uuid;

  select id into v_location
  from location where business_id = v_business and active order by created_at limit 1;

  insert into shop_order (
    client_ref, business_id, location_id, customer_id, status,
    fulfilment, delivery_detail, subtotal, delivery_fee, total,
    currency_code, source
  ) values (
    v_client_ref, v_business, v_location, v_customer, 'pending',
    coalesce((p->>'fulfilment')::fulfilment_method, 'pickup'),
    coalesce(p->'delivery_detail', '{}'::jsonb),
    0, 0, 0, 'GHS',
    coalesce(p->>'source', 'shop_link')
  )
  returning id into v_order;

  for v_line in select * from jsonb_array_elements(p->'lines')
  loop
    v_qty := (v_line->>'quantity')::numeric;
    if v_qty <= 0 then
      raise exception 'invalid quantity';
    end if;

    -- Server-side price: shop listing override, else base price.
    select ci.id, ci.name, ci.base_price, ci.track_stock, cl.price_override
    into v_item
    from catalogue_item ci
    join channel_listing cl on cl.item_id = ci.id and cl.channel = 'shop' and cl.visible
    where ci.id = (v_line->>'item_id')::uuid
      and ci.business_id = v_business
      and ci.active;

    if not found then
      raise exception 'item unavailable: %', v_line->>'item_id';
    end if;

    v_unit := coalesce(v_item.price_override, v_item.base_price);
    if v_unit is null then
      raise exception 'item has no price: %', v_item.id;
    end if;

    insert into shop_order_line (order_id, item_id, description, quantity, unit_price, line_total)
    values (v_order, v_item.id, v_item.name, v_qty, v_unit, round(v_unit * v_qty, 2));

    v_subtotal := v_subtotal + round(v_unit * v_qty, 2);
    v_line_count := v_line_count + 1;

    if v_item.track_stock and v_location is not null then
      insert into stock_movement (
        client_ref, business_id, location_id, item_id, kind, quantity,
        source_entity_type, source_entity_id, occurred_at
      ) values (
        v_client_ref || ':rsv:' || v_item.id,
        v_business, v_location, v_item.id, 'reservation', -1 * v_qty,
        'shop_order', v_order, now()
      ) on conflict (business_id, client_ref) do nothing;
    end if;
  end loop;

  if v_line_count = 0 then
    raise exception 'order has no lines';
  end if;

  update shop_order set subtotal = v_subtotal, total = v_subtotal where id = v_order;

  -- Customer placed this order themselves: customer-confirmed evidence (RDY-008).
  insert into event_outbox (
    event_type, business_id, location_id, channel, product_set,
    entity_type, entity_id, amount, currency_code, verification,
    payload, business_date
  ) values (
    'shop.order.placed', v_business, v_location, 'customer_web', 'shop',
    'shop_order', v_order, v_subtotal, 'GHS', 'customer_confirmed',
    jsonb_build_object('line_count', v_line_count, 'source', coalesce(p->>'source', 'shop_link')),
    current_date
  );

  return jsonb_build_object('order_id', v_order, 'total', v_subtotal, 'duplicate', false);
end;
$$;

-- advance_shop_order (latest definition was 0011_order_management.sql)
create or replace function advance_shop_order(p jsonb)
returns jsonb
language plpgsql security definer
as $$
declare
  v_order shop_order%rowtype;
  v_to order_status := (p->>'to_status')::order_status;
  v_actor uuid := nullif(p->>'actor_membership_id', '')::uuid;
  v_line record;
  v_event text;
  v_verification text := 'merchant_declared';
begin
  select * into v_order from shop_order where id = (p->>'order_id')::uuid for update;
  if not found then
    raise exception 'order not found';
  end if;

  -- Idempotent: a repeated call that lands on the current state is accepted.
  if v_order.status = v_to then
    return jsonb_build_object('order_id', v_order.id, 'status', v_to, 'unchanged', true);
  end if;

  if not shop_order_can_transition(v_order.status, v_to) then
    raise exception 'illegal transition: % to %', v_order.status, v_to;
  end if;

  update shop_order set status = v_to, updated_at = now() where id = v_order.id;

  -- Stock consequences per destination state.
  if v_to in ('fulfilled', 'cancelled', 'refunded') then
    for v_line in
      select l.item_id, l.variant_id, l.quantity, ci.track_stock
      from shop_order_line l
      join catalogue_item ci on ci.id = l.item_id
      where l.order_id = v_order.id
    loop
      if not v_line.track_stock or v_order.location_id is null then
        continue;
      end if;

      if v_to in ('fulfilled', 'cancelled') then
        -- Release the hold in both cases; the goods either leave for real
        -- (below) or return to being sellable.
        insert into stock_movement (
          client_ref, business_id, location_id, item_id, variant_id,
          kind, quantity, source_entity_type, source_entity_id,
          actor_membership_id, occurred_at
        ) values (
          v_order.id::text || ':rel:' || v_line.item_id,
          v_order.business_id, v_order.location_id, v_line.item_id, v_line.variant_id,
          'reservation_release', v_line.quantity,
          'shop_order', v_order.id, v_actor, now()
        ) on conflict (business_id, client_ref) do nothing;
      end if;

      if v_to = 'fulfilled' then
        insert into stock_movement (
          client_ref, business_id, location_id, item_id, variant_id,
          kind, quantity, source_entity_type, source_entity_id,
          actor_membership_id, occurred_at
        ) values (
          v_order.id::text || ':sale:' || v_line.item_id,
          v_order.business_id, v_order.location_id, v_line.item_id, v_line.variant_id,
          'sale', -1 * v_line.quantity,
          'shop_order', v_order.id, v_actor, now()
        ) on conflict (business_id, client_ref) do nothing;
      elsif v_to = 'refunded' then
        insert into stock_movement (
          client_ref, business_id, location_id, item_id, variant_id,
          kind, quantity, source_entity_type, source_entity_id,
          reason, actor_membership_id, occurred_at
        ) values (
          v_order.id::text || ':ret:' || v_line.item_id,
          v_order.business_id, v_order.location_id, v_line.item_id, v_line.variant_id,
          'customer_return', v_line.quantity,
          'shop_order', v_order.id,
          coalesce(p->>'reason', 'order refunded'), v_actor, now()
        ) on conflict (business_id, client_ref) do nothing;
      end if;
    end loop;
  end if;

  -- Financial consequence: fulfilment recognises revenue, refund reverses it.
  if v_to = 'fulfilled' then
    insert into ledger_entry (
      business_id, location_id, kind, amount, currency_code,
      source_entity_type, source_entity_id, business_date
    ) values (
      v_order.business_id, v_order.location_id, 'sale_revenue',
      v_order.total, v_order.currency_code, 'shop_order', v_order.id, current_date
    );
  elsif v_to = 'refunded' then
    insert into ledger_entry (
      business_id, location_id, kind, amount, currency_code,
      source_entity_type, source_entity_id, business_date
    ) values (
      v_order.business_id, v_order.location_id, 'refund',
      -1 * v_order.total, v_order.currency_code, 'shop_order', v_order.id, current_date
    );
  end if;

  v_event := case v_to
    when 'fulfilled' then 'shop.order.fulfilled'
    when 'cancelled' then 'shop.order.cancelled'
    when 'refunded' then 'shop.order.refunded'
    else 'shop.order.progressed'
  end;

  insert into event_outbox (
    event_type, business_id, location_id, actor_membership_id,
    channel, product_set, entity_type, entity_id,
    amount, currency_code, verification, payload, business_date
  ) values (
