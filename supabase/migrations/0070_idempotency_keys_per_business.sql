-- ---------------------------------------------------------------------------
-- 0070  An idempotency key belongs to a business, not to the platform
--
-- Nine tables carry a client_ref that makes a retried request safe to
-- repeat: sale, payment, shop_order, stock_movement, pos_shift,
-- attendance_record, till_expense, message and document. Each was declared
-- `client_ref text unique`, so the key was unique across every business on
-- the platform.
--
-- That is wrong in two directions.
--   * A collision is a cross-tenant event. complete_pos_sale_safe asks
--     "does a sale with this key exist?" with no business in the question; if
--     another business held the key it would conclude this sale had already
--     landed and skip it. place_shop_order and book_service answer a replay by
--     returning the existing row, which would hand one business the order or
--     booking id of another.
--   * Two public endpoints take the key from the customer's browser
--     (/api/shop/orders and /api/services/book), so a key is not always one
--     the platform generated.
-- The offline till generates ULIDs and most other keys are derived from row
-- ids, so a collision is unlikely today. It is still the wrong thing to leave
-- as the foundation, and the cost of fixing it is lowest now.
--
-- THE CHANGE
--   1. The global unique rule on client_ref is dropped on all nine tables and
--      replaced by a unique index on (business_id, client_ref).
--   2. Every `on conflict (client_ref)` must name the new index or the
--      statement stops working, so the thirteen functions that carry one are
--      replaced. Their replay lookups gain the business, so a repeated
--      request is only ever matched to the same business's row.
--
-- HOW THE FUNCTIONS WERE WRITTEN
--   Each is the LATEST definition across migrations 0001 to 0069 with exact,
--   counted substitutions and nothing else (the file was generated, and the
--   generator aborts if any substitution does not match exactly the expected
--   number of times). 0064 regressed a function by rewriting it from the wrong
--   source; this cannot, because it never retypes a body.
--
-- ONE BEHAVIOURAL ADDITION
--   close_pos_shift is handed only the shift's key and has never been told
--   which business. That was safe while the key was globally unique and would
--   not be once it is not. It now uses business_id when the caller sends one
--   (the till sync route now does), and refuses an ambiguous key with
--   'ambiguous_shift_reference' when the caller does not. A caller that does
--   not send business_id keeps working until the key is actually ambiguous,
--   so this migration is safe to run before the code that sends it.
--
-- ROLLOUT ORDER
--   Run this migration, then deploy the app. Nothing in the app breaks in
--   between.
--
-- Tables and columns touched (all checked against the live schema):
--   client_ref and business_id on: stock_movement, pos_shift, sale, document, payment, attendance_record, till_expense, message, shop_order
--   service_booking.completion_detail and business_id (book_service lookup)
--   refund_request.business_id, payment_intent.business_id,
--   sale.business_id (lookups)
-- No column is added or removed. Function signatures and return types are
-- unchanged, so create or replace is enough.
--
-- Not changed: payment_intent.reference (generated by us and sent to the
-- provider, so global by nature), (provider, external_id) and
-- (provider, provider_reference) (assigned by the provider).
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- 0. Pre-flight. Change nothing unless every function that names the old
-- rule is one this migration replaces. A function edited by hand in the SQL
-- editor, or one these files do not know about, would otherwise be left
-- calling an `on conflict` that no longer matches anything and start failing
-- on its first insert. Better to stop here, with the name, than to find out
-- from a customer.
-- ---------------------------------------------------------------------------
do $do$
declare
  v_unknown text;
begin
  select string_agg(p.proname, ', ' order by p.proname) into v_unknown
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace and n.nspname = 'public'
  where p.prosrc ~* 'on\s+conflict\s*\(\s*client_ref\s*\)'
    and p.proname not in ('complete_pos_sale', 'complete_pos_sale_safe', 'place_shop_order', 'advance_shop_order', 'open_pos_shift', 'close_pos_shift', 'queue_message', 'confirm_payment_intent', 'book_service', 'record_attendance', 'complete_refund', 'execute_sale_reversal', 'record_stock_movement');

  if v_unknown is not null then
    raise exception
      '0070 stopped before changing anything: % also name(s) the old client_ref rule and this migration does not replace them',
      v_unknown;
  end if;
end
$do$;

-- ---------------------------------------------------------------------------
-- 1. Drop the global rule, add the per-business one.
--
-- The old constraint is found by what it says, not by its generated name, so
-- this does not depend on what Postgres happened to call it.
-- ---------------------------------------------------------------------------
do $do$
declare
  t text;
  c record;
  v_dropped int := 0;
begin
  foreach t in array array['stock_movement', 'pos_shift', 'sale', 'document', 'payment', 'attendance_record', 'till_expense', 'message', 'shop_order']
  loop
    for c in
      select conname
      from pg_constraint
      where conrelid = format('public.%I', t)::regclass
        and contype = 'u'
        and pg_get_constraintdef(oid) = 'UNIQUE (client_ref)'
    loop
      execute format('alter table public.%I drop constraint %I', t, c.conname);
      v_dropped := v_dropped + 1;
    end loop;

    execute format(
      'create unique index if not exists %I on public.%I (business_id, client_ref)',
      t || '_client_ref_per_business', t
    );
  end loop;

  -- Self-check: no table may still be unique on client_ref alone, whatever
  -- it was called. If one is, the cross-tenant collision would silently
  -- survive, so refuse to finish.
  foreach t in array array['stock_movement', 'pos_shift', 'sale', 'document', 'payment', 'attendance_record', 'till_expense', 'message', 'shop_order']
  loop
    if exists (
      select 1
      from pg_index i
      where i.indrelid = format('public.%I', t)::regclass
        and i.indisunique
        and i.indnatts = 1
        and i.indkey[0] = (
          select a.attnum from pg_attribute a
          where a.attrelid = i.indrelid and a.attname = 'client_ref'
        )
    ) then
      raise exception '0070: % is still unique on client_ref alone', t;
    end if;
  end loop;

  raise notice 'dropped % global client_ref rule(s); per-business index in place on % tables',
    v_dropped, array_length(array['stock_movement', 'pos_shift', 'sale', 'document', 'payment', 'attendance_record', 'till_expense', 'message', 'shop_order'], 1);
end
$do$;

