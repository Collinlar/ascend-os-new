// The review before switching (21-22 Nov 2026 onwards).
//
//   node scripts/review-switches.mjs [--since=2026-11-15] [--out=path.md]
//   --include-test also counts throwaway "ZZ" businesses: for testing this
//   script, never for the real review.
//
// Reads the live database (service role, from .env.local) and writes one
// page answering the questions that decide the switches:
//   0. Was there enough real use to judge anything?
//   1. Commerce core: is the reconciliation zero, and did anything fail to
//      copy in the window? (PHASE_2_PLAN.md)
//   2. Screens: is every difference between today's figures and the core's
//      one of the predicted causes? (PHASE_2D_PLAN.md section 3)
//   3. Permissions: who would the checks have refused, and is any of it a
//      real member blocked from normal work? (PHASE_1_PLAN.md section 4)
// Read only. Business ids are shortened; no names, phone numbers or
// amounts per customer are written.

import fs from "fs";
import path from "path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, "").split("=")));
const since = args.since ?? "2026-11-15";
const today = new Date().toISOString().slice(0, 10);
const out = args.out ?? path.join(ROOT, "docs/planning/2026-11-foundation-alignment/reviews", `review-${today}.md`);

const env = Object.fromEntries(
  fs.readFileSync(path.join(ROOT, ".env.local"), "utf8").split(/\r?\n/)
    .filter((l) => l.includes("=") && !l.trim().startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()])
);
const KEY = env.NEXT_SERVICE_ROLE_KEY ?? env.SUPABASE_SECRET_KEY ?? env.SUPABASE_SERVICE_ROLE_KEY;
const BASE = (env.NEXT_PUBLIC_SUPABASE_URL ?? env.SUPABASE_URL) + "/rest/v1/";
const H = { apikey: KEY, authorization: "Bearer " + KEY, "content-type": "application/json" };

async function all(pathQuery) {
  const rows = [];
  for (let from = 0; ; from += 1000) {
    const r = await fetch(BASE + pathQuery, { headers: { ...H, range: `${from}-${from + 999}` } });
    if (!r.ok) throw new Error(`${pathQuery}: ${await r.text()}`);
    const page = await r.json();
    rows.push(...page);
    if (page.length < 1000) return rows;
  }
}
async function rpc(name, body) {
  const r = await fetch(BASE + "rpc/" + name, { method: "POST", headers: H, body: JSON.stringify(body) });
  if (!r.ok) throw new Error(`${name}: ${await r.text()}`);
  return r.json();
}
const short = (id) => (id ? String(id).slice(0, 8) : "none");
const money = (n) => `GHS ${Number(n).toLocaleString("en-GH", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const r2 = (n) => Math.round(Number(n) * 100) / 100;
const lines = [];
const say = (s = "") => lines.push(s);
const verdicts = [];

// Test data never counts: throwaway businesses are named "ZZ ...".
const businesses = await all("business?select=id,name");
const includeTest = "include-test" in args;
const testBiz = new Set(includeTest ? [] : businesses.filter((b) => /^ZZ\b/.test(b.name ?? "")).map((b) => b.id));
const real = (row) => !testBiz.has(row.business_id);

say(`# Review before switching: ${today}`);
say();
say(`Window: ${since} to ${today}. Generated by \`scripts/review-switches.mjs\`. Read only.`);
say();

// ---------------------------------------------------------------------------
// 0. Traffic
// ---------------------------------------------------------------------------
say(`## 0. Was there enough real use to judge?`);
say();
const sinceTs = `${since}T00:00:00Z`;
const traffic = [
  ["Sign-ins", (await all(`auth_session?created_at=gte.${sinceTs}&select=person_id`)).length],
  ["Till sales", (await all(`sale?occurred_at=gte.${sinceTs}&select=business_id`)).filter(real).length],
  ["Shop orders", (await all(`shop_order?placed_at=gte.${sinceTs}&select=business_id`)).filter(real).length],
  ["Bookings", (await all(`service_booking?created_at=gte.${sinceTs}&select=business_id`)).filter(real).length],
  ["Documents", (await all(`document?created_at=gte.${sinceTs}&select=business_id`)).filter(real).length],
  ["Payments", (await all(`payment?occurred_at=gte.${sinceTs}&select=business_id`)).filter(real).length],
];
const permissionRows = (await all(`authority_decision?at=gte.${sinceTs}&select=at,mode,surface,route,method,action,role,decision,reason,business_id,person_id,required`))
  .filter((r) => !r.business_id || real(r));
traffic.push(["Permission checks logged", permissionRows.length]);
say(`| What | In the window |`);
say(`|---|---|`);
for (const [k, v] of traffic) say(`| ${k} | ${v} |`);
say();
const commerceActivity = traffic.slice(1, 6).reduce((n, [, v]) => n + v, 0);
const enoughCommerce = commerceActivity >= 20;
const enoughPermission = permissionRows.length >= 50;
say(enoughCommerce
  ? `Commerce activity: ${commerceActivity} records, enough to judge the commerce core and the screens.`
  : `**Commerce activity: ${commerceActivity} records. Too little to judge.** A clean result below means nothing went wrong in a window where almost nothing happened.`);
say();
say(enoughPermission
  ? `Permission checks: ${permissionRows.length} logged, enough to judge.`
  : `**Permission checks: ${permissionRows.length} logged. Too little to judge** switching any group on from the log alone.`);
say();
verdicts.push(`Traffic: ${enoughCommerce ? "enough" : "TOO LITTLE"} commerce activity (${commerceActivity}), ${enoughPermission ? "enough" : "TOO LITTLE"} permission checks (${permissionRows.length}).`);

// ---------------------------------------------------------------------------
// 1. Commerce core
// ---------------------------------------------------------------------------
say(`## 1. Commerce core`);
say();
const recon = (await rpc("commerce_reconciliation", {})).filter(real);
const projErrors = (await all(`commerce_projection_error?at=gte.${sinceTs}&select=at,origin_type,origin_id,business_id,error`)).filter((r) => !r.business_id || real(r));
if (recon.length === 0) say(`The reconciliation returns **zero differences** now.`);
else {
  say(`The reconciliation returns **${recon.length} difference(s)** now:`);
  say();
  say(`| Check | Record | Expected | Found |`);
  say(`|---|---|---|---|`);
  for (const d of recon.slice(0, 50)) say(`| ${d.check_name} | ${d.origin_type} ${short(d.origin_id)} | ${d.expected} | ${d.found} |`);
}
say();
say(projErrors.length === 0
  ? `Nothing failed to copy into the core in the window.`
  : `**${projErrors.length} record(s) failed to copy** in the window (commerce_projection_error): ${projErrors.slice(0, 10).map((e) => `${e.origin_type} ${short(e.origin_id)}: ${e.error}`).join("; ")}`);
say();
say(`*Limit:* the reconciliation is a check of now. Nothing records it day by day, so "zero all week" rests on zero now plus no copy failures in the window.`);
say();
verdicts.push(`Commerce core: ${recon.length === 0 && projErrors.length === 0 ? "clean" : `${recon.length} difference(s), ${projErrors.length} copy failure(s)`}.`);

// ---------------------------------------------------------------------------
// 2. Screens: today's figures against the core's
// ---------------------------------------------------------------------------
say(`## 2. Screens: every difference explained?`);
say();
const comparisons = (await all(`commerce_reader_comparison?day=gte.${since}&select=business_id,screen,figure,day,current_value,core_value,times_seen&order=day.desc`)).filter(real);
if (comparisons.length === 0) {
  say(`No differences were recorded in the window. ${enoughCommerce ? "" : "With so little activity, that is expected and proves little."}`);
  say();
} else {
  const byFigure = {};
  for (const c of comparisons) (byFigure[`${c.screen} / ${c.figure}`] ??= []).push(c);
  say(`| Screen / figure | Business-days with a difference | Loads |`);
  say(`|---|---|---|`);
  for (const [k, v] of Object.entries(byFigure)) say(`| ${k} | ${v.length} | ${v.reduce((n, c) => n + c.times_seen, 0)} |`);
  say();
}

// Explain today's differences, per business, record by record.
const txAll = (await all("commercial_transaction?select=id,business_id,origin_type,origin_id,transaction_type,product_status,status,customer_id,total,earned_at")).filter(real);
const txById = new Map(txAll.map((t) => [t.id, t]));
const balances = (await all("obligation_balance?select=obligation_id,transaction_id,business_id,status,outstanding,amount_paid,amount_credited")).filter(real);
const links = await all("commerce_document_link?select=document_id,transaction_id,role");
const linkByDoc = new Map(links.map((l) => [l.document_id, l]));
// The same rule as commerce_is_committed() (0087): accepted by the merchant,
// read from the product's own status, and not refunded in full.
const committed = (t) => {
  const p = t.product_status;
  const base =
    ["draft", "pending_approval", "change_requested", "held"].includes(p) ? "draft"
    : ["cancelled", "no_show", "rejected", "expired"].includes(p) ? "cancelled"
    : ["reversed", "superseded"].includes(p) ? "reversed"
    : ["pending", "requested", "quoted"].includes(p) ? "pending"
    : "other";
  return !["draft", "cancelled", "reversed"].includes(base)
    && (t.origin_type === "document" || base !== "pending")
    && t.status !== "refunded";
};
const coreOwedByTx = new Map();
for (const b of balances) {
  const t = txById.get(b.transaction_id);
  if (!t || ["cancelled", "written_off"].includes(b.status) || !(Number(b.outstanding) > 0) || !committed(t)) continue;
  coreOwedByTx.set(t.id, r2((coreOwedByTx.get(t.id) ?? 0) + Number(b.outstanding)));
}

const activeBiz = [...new Set([...comparisons.map((c) => c.business_id), ...txAll.map((t) => t.business_id)])];
const explained = [];
const unexplained = [];
const receivables = (await all("receivable?settled_at=is.null&select=business_id,source_entity_type,source_entity_id,amount_due,amount_paid")).filter(real);
const docs = (await all("document?select=id,business_id,type,status,customer_id,total,number,converted_from")).filter(real);
const docById = new Map(docs.map((d) => [d.id, d]));
const creditedByDoc = new Map();
for (const d of docs) if (d.type === "credit_note" && d.converted_from && !["draft", "cancelled"].includes(d.status)) creditedByDoc.set(d.converted_from, r2((creditedByDoc.get(d.converted_from) ?? 0) + Math.abs(Number(d.total ?? 0))));

for (const biz of activeBiz) {
  // Dashboard "owed": receivables (today) against committed obligations (core).
  const curByTx = new Map();
  const recCount = new Map();
  for (const r of receivables.filter((x) => x.business_id === biz)) {
    const out = Math.max(0, Number(r.amount_due) - Number(r.amount_paid));
    const tx = linkByDoc.get(r.source_entity_id)?.transaction_id ?? null;
    if (!tx) { if (out > 0) unexplained.push(`Business ${short(biz)}: owed: receivable for document ${short(r.source_entity_id)} (${money(out)}) has no transaction in the core`); continue; }
    curByTx.set(tx, r2((curByTx.get(tx) ?? 0) + out));
    recCount.set(tx, (recCount.get(tx) ?? 0) + 1);
  }
  const txIds = new Set([...curByTx.keys(), ...[...coreOwedByTx.keys()].filter((id) => txById.get(id)?.business_id === biz)]);
  for (const id of txIds) {
    const cur = curByTx.get(id) ?? 0, core = coreOwedByTx.get(id) ?? 0;
    if (Math.abs(cur - core) < 0.005) continue;
    const t = txById.get(id);
    const doc = t?.origin_type === "document" ? docById.get(t.origin_id) : null;
    let cause = null;
    if (t && t.origin_type !== "document") cause = "the core counts confirmed orders and bookings; receivables only cover invoices";
    else if ((recCount.get(id) ?? 0) > 1) cause = "a proforma converted to an invoice has two receivables";
    else if (t && t.status === "refunded") cause = "refunded or credited in full: the core says nothing is owed";
    else if (doc && (creditedByDoc.get(doc.id) ?? 0) > 0) cause = "receivables ignore credit notes";
    else if (doc && !doc.customer_id) cause = "an invoice with no customer has no receivable";
    const lineText = `Business ${short(biz)}: owed on ${t?.origin_type ?? "?"} ${short(t?.origin_id)}: today ${money(cur)}, core ${money(core)}`;
    (cause ? explained : unexplained).push(cause ? `${lineText}: ${cause}` : lineText);
  }
}
// Today's received and sales, per business, from the comparison rows for today.
for (const c of comparisons.filter((x) => x.day === today && ["received_today", "verified_received"].includes(x.figure))) {
  const pays = (await all(`payment?business_id=eq.${c.business_id}&status=eq.confirmed&occurred_at=gte.${today}T00:00:00Z&select=amount,source_entity_type,verification`));
  const topups = pays.filter((p) => !["sale", "shop_order", "service_booking", "document"].includes(p.source_entity_type));
  const topTotal = r2(topups.filter((p) => c.figure === "received_today" || p.verification === "provider_confirmed").reduce((n, p) => n + Number(p.amount), 0));
  const refunds = c.figure === "received_today" ? r2((await all(`commerce_adjustment?business_id=eq.${c.business_id}&kind=eq.refund&occurred_at=gte.${today}T00:00:00Z&select=amount`)).reduce((n, j) => n + Number(j.amount), 0)) : 0;
  const diff = r2(Number(c.current_value) - Number(c.core_value));
  const lineText = `Business ${short(c.business_id)}: ${c.figure}: today ${money(c.current_value)}, core ${money(c.core_value)}`;
  if (Math.abs(diff - (topTotal + refunds)) < 0.005) explained.push(`${lineText}: Ascend Balance top-ups ${money(topTotal)}${refunds ? ` and refunds ${money(refunds)}` : ""}, counted today, not by the core`);
  else unexplained.push(`${lineText} (top-ups ${money(topTotal)}, refunds ${money(refunds)} explain ${money(topTotal + refunds)} of ${money(diff)})`);
}
for (const c of comparisons.filter((x) => x.day === today && ["sales_today", "sale_count"].includes(x.figure))) {
  const earned = txAll.filter((t) => t.business_id === c.business_id && t.earned_at?.slice(0, 10) === today && !["draft", "cancelled", "reversed"].includes(t.status));
  const extra = earned.filter((t) => ["document", "service_booking"].includes(t.origin_type));
  const adj = (await all(`commerce_adjustment?business_id=eq.${c.business_id}&occurred_at=gte.${today}T00:00:00Z&select=kind,amount,transaction_id`));
  const givenBack = r2(adj.filter((j) => ["refund", "credit", "return"].includes(j.kind)).reduce((n, j) => n + Number(j.amount), 0));
  const reversedEarlier = r2(adj.filter((j) => j.kind === "reversal" && (txById.get(j.transaction_id)?.earned_at ?? today) < today).reduce((n, j) => n + Number(j.amount), 0));
  const expectDiff = c.figure === "sale_count" ? extra.length : r2(extra.reduce((n, t) => n + Number(t.total), 0) - givenBack - reversedEarlier);
  const diff = r2(Number(c.core_value) - Number(c.current_value));
  const lineText = `Business ${short(c.business_id)}: ${c.figure}: today ${c.figure === "sale_count" ? c.current_value : money(c.current_value)}, core ${c.figure === "sale_count" ? c.core_value : money(c.core_value)}`;
  if (Math.abs(diff - expectDiff) < 0.005) explained.push(`${lineText}: the core counts ${extra.length} booking(s) and invoice(s) earned today${c.figure === "sales_today" && (givenBack || reversedEarlier) ? `, less ${money(givenBack + reversedEarlier)} given back or reversed` : ""}`);
  else unexplained.push(`${lineText} (bookings, invoices and adjustments explain ${expectDiff} of ${diff})`);
}
// Customers list: whole-business owed and spent totals, record by record.
const custRows = comparisons.filter((x) => x.day === today && x.screen === "customers");
for (const c of custRows) {
  const biz = c.business_id;
  const diff = r2(Number(c.current_value) - Number(c.core_value));
  const lineText = `Business ${short(biz)}: customers ${c.figure}: today ${money(c.current_value)}, core ${money(c.core_value)}`;
  const parts = [];
  if (c.figure === "owed_total") {
    // Today: the full total of every open invoice with a customer.
    // Core: committed outstanding on every customer's transactions.
    const open = docs.filter((d) => d.business_id === biz && d.type === "invoice" && d.number && d.customer_id
      && ["issued", "sent", "delivered", "viewed", "partially_paid", "overdue"].includes(d.status));
    const curByTx = new Map();
    for (const d of open) {
      const tx = linkByDoc.get(d.id)?.transaction_id;
      if (tx) curByTx.set(tx, r2((curByTx.get(tx) ?? 0) + Number(d.total ?? 0)));
    }
    const ids = new Set([...curByTx.keys(), ...[...coreOwedByTx.keys()].filter((id) => txById.get(id)?.business_id === biz && txById.get(id)?.customer_id)]);
    let accounted = 0;
    for (const id of ids) {
      const cur = curByTx.get(id) ?? 0, core = coreOwedByTx.get(id) ?? 0;
      if (Math.abs(cur - core) < 0.005) continue;
      const t = txById.get(id);
      const b = balances.filter((x) => x.transaction_id === id);
      const paid = b.reduce((n, x) => n + Number(x.amount_paid), 0);
      const credited = b.reduce((n, x) => n + Number(x.amount_credited), 0);
      const why = t.origin_type !== "document" ? "the core counts confirmed orders and bookings"
        : t.transaction_type === "proforma" ? "the core counts proformas; the list counts invoices only"
        : paid > 0 || credited > 0 ? `the list ignores ${[paid > 0 ? `${money(paid)} paid` : "", credited > 0 ? `${money(credited)} credited` : ""].filter(Boolean).join(" and ")}`
        : t.status === "refunded" ? "refunded in full: the core says nothing is owed"
        : null;
      if (!why) { unexplained.push(`${lineText}: ${t.origin_type} ${short(t.origin_id)} differs (${money(cur)} vs ${money(core)}) for no known reason`); continue; }
      parts.push(`${t.origin_type} ${short(t.origin_id)}: ${why}`);
      accounted = r2(accounted + cur - core);
    }
    if (Math.abs(accounted - diff) < 0.005) explained.push(`${lineText}: ${parts.join("; ")}`);
    else unexplained.push(`${lineText} (the records explain ${money(accounted)} of ${money(diff)})`);
  } else if (c.figure === "spent_total") {
    // Today: confirmed payments by customer. Core: paid less refunds on the
    // customer's transactions.
    const refunds = r2((await all(`commerce_adjustment?business_id=eq.${biz}&kind=eq.refund&select=amount,transaction_id`))
      .filter((j) => txById.get(j.transaction_id)?.customer_id).reduce((n, j) => n + Number(j.amount), 0));
    if (Math.abs(diff - refunds) < 0.005) explained.push(`${lineText}: refunds of ${money(refunds)}, which the list does not subtract`);
    else unexplained.push(`${lineText} (refunds explain ${money(refunds)} of ${money(diff)})`);
  }
}
// The other "owed" figures (customers owing, overdue count and amount,
// oldest overdue) follow from the same records as owed itself: explained
// when every owed difference for that business is explained.
const OWED_FAMILY = ["owed_customers", "overdue_count", "overdue_amount", "oldest_owed_days"];
for (const c of comparisons.filter((x) => x.day === today && x.screen === "dashboard" && OWED_FAMILY.includes(x.figure))) {
  const lineText = `Business ${short(c.business_id)}: ${c.figure}: today ${c.current_value}, core ${c.core_value}`;
  const owedUnexplained = unexplained.some((u) => u.startsWith(`Business ${short(c.business_id)}: owed`));
  const owedExplained = explained.filter((e) => e.startsWith(`Business ${short(c.business_id)}: owed on`));
  if (!owedUnexplained && owedExplained.length) explained.push(`${lineText}: follows from the owed difference(s) above`);
  else unexplained.push(`${lineText} (no explained owed difference for this business to account for it)`);
}
// Nothing recorded today may go unchecked.
const CHECKED = new Set(["owed", ...OWED_FAMILY, "received_today", "verified_received", "sales_today", "sale_count", "owed_total", "spent_total"]);
for (const c of comparisons.filter((x) => x.day === today && !CHECKED.has(x.figure))) {
  unexplained.push(`Business ${short(c.business_id)}: ${c.screen} ${c.figure}: today ${c.current_value}, core ${c.core_value} (this report does not check this figure)`);
}
const olderDays = comparisons.filter((c) => c.day !== today && !["owed", "owed_customers", "overdue_count", "overdue_amount", "oldest_owed_days"].includes(c.figure));
say(`### Unexplained`);
say();
if (unexplained.length === 0) say(`None.`); else for (const u of unexplained) say(`- **${u}**`);
say();
say(`### Explained by a predicted cause`);
say();
if (explained.length === 0) say(`None.`); else for (const e of explained) say(`- ${e}`);
say();
if (olderDays.length) {
  say(`*Earlier days:* ${olderDays.length} difference(s) on sales or money received recorded before today. Those figures are for a day that has passed and are not re-derived here; check them against the activity of that day if any look large.`);
  say();
}
verdicts.push(`Screens: ${unexplained.length === 0 ? "every difference explained" : `${unexplained.length} UNEXPLAINED difference(s)`} (${explained.length} explained${comparisons.length ? `, ${comparisons.length} recorded in the window` : ", none recorded"}).`);

// ---------------------------------------------------------------------------
// 3. Permissions
// ---------------------------------------------------------------------------
say(`## 3. Permissions (Phase 1 shadow log)`);
say();
const enforceSrc = fs.readFileSync(path.join(ROOT, "lib/authority/enforce.ts"), "utf8");
const groupOf = {};
for (const [, key, group] of enforceSrc.matchAll(/^\s*"?([\w/\[\]-]+)"?:\s*"(\w+)",\s*$/gm)) groupOf[key] = group;
const shadow = permissionRows.filter((r) => r.mode === "shadow");
const groups = {};
for (const r of shadow) {
  const g = groupOf[r.route] ?? "(not in a group)";
  const s = (groups[g] ??= { allow: 0, would_deny: 0, not_applicable: 0, error: 0, members: [] });
  s[r.decision] = (s[r.decision] ?? 0) + 1;
  // A signed-in member of the business being refused is the case that matters.
  if (r.decision === "would_deny" && !["not_signed_in", "not_a_platform_admin"].includes(r.reason)) s.members.push(r);
}
if (shadow.length === 0) {
  say(`No permission checks were logged in shadow mode in the window.`);
} else {
  say(`| Group | Allowed | Would refuse | Of which a signed-in member | Errors |`);
  say(`|---|---|---|---|---|`);
  for (const [g, s] of Object.entries(groups).sort()) say(`| ${g} | ${s.allow} | ${s.would_deny} | ${s.members.length} | ${s.error} |`);
  say();
  const members = Object.values(groups).flatMap((s) => s.members);
  say(`### Signed-in members who would have been refused`);
  say();
  if (members.length === 0) say(`None. Every refusal in the window was someone not signed in, or not a platform admin on an admin route.`);
  else {
    const key = (r) => `${r.surface} ${r.route}${r.action ? ` (${r.action})` : ""} | role ${r.role ?? "?"} | ${r.reason}`;
    const counts = {};
    for (const r of members) counts[key(r)] = (counts[key(r)] ?? 0) + 1;
    say(`| Where | Role | Why | Times |`);
    say(`|---|---|---|---|`);
    const ownerFirst = (k) => (k.includes("| role owner |") ? 0 : 1);
    for (const [k, n] of Object.entries(counts).sort((a, b) => ownerFirst(a[0]) - ownerFirst(b[0]) || b[1] - a[1])) {
      const [where, role, why] = k.split(" | ");
      say(`| ${where} | ${role.replace("role ", "")} | ${why} | ${n} |`);
    }
    say();
    say(`Owners refused anywhere are listed first in the review: an owner should only ever be refused for a capability their business has not turned on.`);
  }
}
say();
const memberRefusals = Object.values(groups).reduce((n, s) => n + s.members.length, 0);
verdicts.push(`Permissions: ${shadow.length} shadow checks; ${memberRefusals} would-refuse(s) of a signed-in member.`);

// ---------------------------------------------------------------------------
say(`## Verdict`);
say();
for (const v of verdicts) say(`- ${v}`);
say();
